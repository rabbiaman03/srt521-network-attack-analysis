"""Scripted stand-ins for the model, so the graders run without a provider.

FakeModel follows a script you give it. NotesFake plays the incident-notes
assistant of labs 3 and 5 and is deliberately obedient: it follows any
instruction it can read in a tool result. That makes the guard tests
deterministic. Do not edit this file; the graders import it.
"""
import json
import re
import unicodedata


class FakeModel:
    """A model that replays a script.

    Each step is a dict {"text": "..."} or {"tool_calls": [{"name": ..., "arguments": {...}}]},
    or a callable step(messages, tools, response_schema) -> such a dict. When
    the script runs out the last step repeats, which is how a never-stopping
    model is simulated.
    """

    def __init__(self, script):
        self.script = list(script)
        self.calls = 0

    def __call__(self, messages, tools=None, response_schema=None):
        index = min(self.calls, len(self.script) - 1)
        self.calls += 1
        step = self.script[index]
        if callable(step):
            step = step(messages, tools, response_schema)
        calls = [{"id": f"call_{self.calls}_{i}", "name": c["name"], "arguments": c.get("arguments", {})}
                 for i, c in enumerate(step.get("tool_calls", []))]
        return {"text": step.get("text", ""), "tool_calls": calls,
                "stop": "tool_calls" if calls else "end", "usage": {"input": 0, "output": 0}}


# ------------------------------------------------------------- NotesFake

HOST_RE = re.compile(r"\b(?!note-)[a-z0-9]+(?:-[a-z]+)*-\d{2}\b")
CVE_RE = re.compile(r"\bcve-\d{4}-\d{4}\b")
INSTRUCTION_RE = re.compile(r"run `([^`]+)` with the shell tool", re.IGNORECASE)
SUMMARY_RE = re.compile(r"^([a-z0-9-]+): severity (\S+), status (\S+), action: (.*)$")
ZERO_WIDTH = "\u200b\u200c\u200d\ufeff\u2060"
CONFUSABLES = str.maketrans("аеорсхуАЕОРСХУ", "aeopcxyAEOPCXY")


def read_through(text):
    """What a model 'sees': zero-width characters gone, look-alike letters
    read as the Latin letters they resemble."""
    text = unicodedata.normalize("NFKC", text)
    text = text.translate({ord(ch): None for ch in ZERO_WIDTH})
    return text.translate(CONFUSABLES)


class NotesFake:
    """The incident-notes assistant, scripted.

    Given the task, it searches once per host or CVE named in the request
    (or once with the whole request), follows an instruction of the form
    "run `CMD` with the shell tool" if one appears in a tool result, and then
    answers from what the tool results said. A call with a response_schema
    is treated as a fact-extraction request and a call without tools as a
    summary request, which is how compaction talks to the model.
    """

    def __init__(self, k=1, follow_instructions=True):
        self.k = k
        self.follow = follow_instructions
        self.searches = 0
        self.ran = []

    def __call__(self, messages, tools=None, response_schema=None):
        # Compaction hands the transcript over inside a user message, so the
        # two compaction branches read user content; the agent branch skips
        # it, or the hosts named in the task would appear as empty findings.
        if response_schema is not None:
            facts = self._facts(messages, skip=("system",))
            return self._reply(json.dumps({"facts": facts}, ensure_ascii=False))
        if not tools:
            return self._reply("\n".join(self._facts(messages, skip=("system",))) or "Nothing to summarize.")
        task = next((m["content"] for m in messages if m["role"] == "user"), "")
        queries = HOST_RE.findall(task.lower()) or CVE_RE.findall(task.lower()) or [task]
        last = messages[-1]
        if self.follow and last["role"] == "tool":
            for text in self._texts(last):
                m = INSTRUCTION_RE.search(read_through(text))
                if m and m.group(1) not in self.ran:
                    self.ran.append(m.group(1))
                    return self._call("run_shell", {"command": read_through(m.group(1))})
        if self.searches < len(queries):
            query = queries[self.searches]
            self.searches += 1
            return self._call("search_notes", {"query": query, "k": self.k})
        return self._reply(self._answer(messages))

    # helpers

    def _reply(self, text):
        return {"text": text, "tool_calls": [], "stop": "end", "usage": {"input": 0, "output": 0}}

    def _call(self, name, arguments):
        return {"text": "", "tool_calls": [{"id": f"call_{self.searches}_{len(self.ran)}",
                                            "name": name, "arguments": arguments}],
                "stop": "tool_calls", "usage": {"input": 0, "output": 0}}

    def _texts(self, message):
        """The note texts and shell outputs carried by one message."""
        content = message.get("content") or ""
        try:
            obj = json.loads(content)
        except (json.JSONDecodeError, TypeError):
            return [content.replace("\\n", "\n")]
        if isinstance(obj, dict) and "results" in obj:
            return [r.get("text", "") for r in obj["results"]]
        if isinstance(obj, dict) and "output" in obj:
            return ["SHELL OUTPUT: " + str(obj["output"])]
        return [content]

    def _blocks(self, messages, skip=("system", "user")):
        """Per-host facts seen in tool results and assistant text, plus shell outputs.

        Reads two shapes: a note (title or "Host:" line, then "Severity:",
        "Status:" and an "Action taken" section) and the one-line summary
        _facts() writes, so facts survive a compaction that kept the summary.
        """
        hosts, shell = {}, []
        for m in messages:
            if m["role"] in skip:
                continue
            for text in self._texts(m):
                if text.startswith("SHELL OUTPUT: "):
                    shell.append(text[len("SHELL OUTPUT: "):].strip())
                    continue
                current, expect_action = None, False
                for line in text.splitlines():
                    stripped = line.strip()
                    lower = stripped.lower()
                    m_sum = SUMMARY_RE.match(lower)
                    if m_sum:
                        current = m_sum.group(1)
                        hosts[current] = {"severity": m_sum.group(2), "status": m_sum.group(3),
                                          "action": stripped.split("action: ", 1)[1]}
                        if "rebuilt" in lower:
                            hosts[current]["rebuilt"] = True
                        continue
                    found = HOST_RE.findall(lower)
                    if found:
                        current = found[0]
                        hosts.setdefault(current, {"severity": "?", "status": "?", "action": "?"})
                    if current is None:
                        continue
                    field_line = lower.lstrip("- ")
                    for field in ("severity", "status"):
                        if field_line.startswith(field + ":"):
                            hosts[current][field] = stripped.split(":", 1)[1].strip()
                    if field_line == "## action taken":
                        expect_action = True
                    elif expect_action and stripped:
                        hosts[current]["action"] = stripped
                        expect_action = False
                    if "rebuilt" in lower:
                        hosts[current]["rebuilt"] = True
        return hosts, shell

    def _facts(self, messages, skip=("system", "user")):
        hosts, _ = self._blocks(messages, skip)
        return [f"{h}: severity {v['severity']}, status {v['status']}, action: {v['action']}"
                for h, v in hosts.items()]

    def _answer(self, messages):
        hosts, shell = self._blocks(messages)
        if not hosts:
            return "I found no note about that."
        lines = self._facts(messages)
        rebuilt = [h for h, v in hosts.items() if v.get("rebuilt")]
        text = "Findings:\n" + "\n".join(lines) + f"\nrebuilt: {', '.join(rebuilt) or 'unknown'}"
        if shell:
            text += "\nOutput: " + " | ".join(shell)
        return text
